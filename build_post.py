import re, sys
src, dst = sys.argv[1], sys.argv[2]
s = open(src, encoding='utf-8').read()
assert '<html' in s and 'id="awards"' in s, 'dump failed'
s = re.sub(r'^\s*<!DOCTYPE[^>]*>\s*', '', s, flags=re.I)
s = re.sub(r'<html[^>]*>', '<html lang="en">', s, count=1)
s = re.sub(r'<body[^>]*>', '<body>', s, count=1)
assert '>Recording Academy' in s or 'Recording Academy' in s, 'content not rendered'
out = '<!doctype html>\n<!-- Generated by build.sh from src/index.html. Edit src/index.html, then run ./build.sh -->\n' + s + '\n'
open(dst, 'w', encoding='utf-8').write(out)
